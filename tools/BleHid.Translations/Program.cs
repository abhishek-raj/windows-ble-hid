using System.Text.Json;
using System.Text.RegularExpressions;
using BleHid.Localization;
using BleHid.Translations;

// Usage:
//   check [--fix]                          verify translation files and generated Android strings
//   issue validate --event <file> --comment <file>
//   issue apply --event <file> --out <directory>
// See TRANSLATING.md. Event files are the JSON GitHub Actions provides in GITHUB_EVENT_PATH.

var repository = TranslationRepository.Find(Directory.GetCurrentDirectory());

string? Option(string name)
{
    var index = Array.IndexOf(args, name);
    return index >= 0 && index + 1 < args.Length ? args[index + 1] : null;
}

switch (args.FirstOrDefault())
{
    case "check":
        return Check.Run(repository, fix: args.Contains("--fix"), Console.Out);

    case "issue" when args.Length > 1 && args[1] is "validate" or "apply":
    {
        var eventPath = Option("--event") ?? throw new ArgumentException("--event is required");
        var issue = GitHubIssue.Read(eventPath);
        var review = IssueReview.Create(repository, issue.Body);

        if (args[1] == "validate")
        {
            var commentPath = Option("--comment") ?? throw new ArgumentException("--comment is required");
            File.WriteAllText(commentPath, review.Comment());
            Outputs.Write("valid", review.IsValid ? "true" : "false");
            Console.WriteLine(review.IsValid ? "valid" : "needs changes");
            return 0;
        }

        if (!review.IsValid)
        {
            Console.Error.WriteLine("the submission does not pass validation; see the issue comment");
            return 1;
        }

        var outDirectory = Option("--out") ?? throw new ArgumentException("--out is required");
        Directory.CreateDirectory(outDirectory);
        var language = review.Language!;
        repository.Write(language, review.Merged!);
        Check.Run(repository, fix: true, TextWriter.Null);

        var name = Loc.NativeName(language);
        var english = System.Globalization.CultureInfo.GetCultureInfo(language).EnglishName;
        var verb = review.IsNewLanguage ? "Add" : "Update";
        File.WriteAllText(Path.Combine(outDirectory, "commit-message.txt"),
            $"{verb} {english} translation\n\nSubmitted in #{issue.Number}.\n\n{issue.CoAuthorTrailer}\n");
        File.WriteAllText(Path.Combine(outDirectory, "pr-body.md"),
            $"{verb}s the {english} ({name}, `{language}`) translation submitted by @{issue.Login} in #{issue.Number}.\n\n"
            + $"- {review.Report!.Accepted.Count} strings: {review.NewStrings} new, {review.ChangedStrings} changed\n"
            + $"- {review.StillEnglish.Count} strings still fall back to English\n\n"
            + "Generated by the translation workflow from the approved issue. Android resources were regenerated.\n\n"
            + $"Closes #{issue.Number}\n");
        Outputs.Write("language", language);
        Outputs.Write("title", $"{verb} {english} translation");
        Console.WriteLine($"wrote {language}");
        return 0;
    }

    default:
        Console.Error.WriteLine("usage: check [--fix] | issue validate --event <file> --comment <file> | issue apply --event <file> --out <dir>");
        return 2;
}

/// <summary>The parts of the GitHub issue event the tool uses.</summary>
internal sealed partial record GitHubIssue(int Number, string? Body, string Login, long UserId)
{
    /// <summary>GitHub links commits to the translator's profile through their no-reply address.</summary>
    public string CoAuthorTrailer => $"Co-authored-by: {Login} <{UserId}+{Login}@users.noreply.github.com>";

    public static GitHubIssue Read(string path)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(path));
        var issue = document.RootElement.GetProperty("issue");
        var user = issue.GetProperty("user");
        var login = user.GetProperty("login").GetString() ?? string.Empty;
        // Interpolated into a commit message, so anything unexpected is refused outright.
        if (!LoginPattern().IsMatch(login)) throw new InvalidDataException("unexpected GitHub login");
        return new GitHubIssue(
            issue.GetProperty("number").GetInt32(),
            issue.TryGetProperty("body", out var body) ? body.GetString() : null,
            login,
            user.GetProperty("id").GetInt64());
    }

    [GeneratedRegex(@"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$")]
    private static partial Regex LoginPattern();
}

/// <summary>Step outputs for GitHub Actions; ignored when run locally.</summary>
internal static class Outputs
{
    public static void Write(string name, string value)
    {
        var path = Environment.GetEnvironmentVariable("GITHUB_OUTPUT");
        if (!string.IsNullOrEmpty(path)) File.AppendAllText(path, $"{name}={value}\n");
    }
}
